package probe

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/netip"
	"syscall"
	"time"
	"unsafe"
)

// Windows has no unprivileged ICMP socket, but the IP Helper API sends echoes for any user. Only the
// standard library is used: iphlpapi.dll is registered by the net package as a system DLL, so
// LazyDLL loads it from System32 only (no DLL search-path hijacking).
var (
	iphlpapi            = syscall.NewLazyDLL("iphlpapi.dll")
	procIcmpCreateFile  = iphlpapi.NewProc("IcmpCreateFile")
	procIcmpCloseHandle = iphlpapi.NewProc("IcmpCloseHandle")
	procIcmpSendEcho    = iphlpapi.NewProc("IcmpSendEcho")
)

const invalidHandle = ^uintptr(0)

// ipOptionInformation mirrors IP_OPTION_INFORMATION; Go's alignment rules give it the same layout as
// the C struct on 386, amd64 and arm64.
type ipOptionInformation struct {
	TTL         uint8
	TOS         uint8
	Flags       uint8
	OptionsSize uint8
	OptionsData uintptr
}

// icmpEchoReply mirrors ICMP_ECHO_REPLY.
type icmpEchoReply struct {
	Address       uint32 // network byte order, like the request address
	Status        uint32
	RoundTripTime uint32 // milliseconds
	DataSize      uint16
	Reserved      uint16
	Data          uintptr
	Options       ipOptionInformation
}

// IP_STATUS values (ipexport.h) live in [ipStatusBase, ipStatusBase+50]: they all describe a host
// that did not answer (timeout, unreachable…), as opposed to an API failure.
const (
	ipSuccess               = 0
	ipStatusBase            = 11000
	errorNetworkUnreachable = syscall.Errno(1231)
	errorHostUnreachable    = syscall.Errno(1232)
)

// echoPayload is the request data; its content is irrelevant, it only has to come back.
var echoPayload = []byte("awake-agent-probe-0123456789abcd")

type icmpPinger struct {
	log *slog.Logger
}

func (p *icmpPinger) ping(ctx context.Context, ip netip.Addr, timeout time.Duration) (Result, error) {
	type outcome struct {
		res Result
		err error
	}
	// IcmpSendEcho blocks for up to timeout and cannot be cancelled; running it in a goroutine lets
	// the caller give up on context cancellation (the goroutine ends on its own within timeout).
	done := make(chan outcome, 1)
	go func() {
		res, err := sendEcho(ip, timeout)
		done <- outcome{res, err}
	}()
	select {
	case o := <-done:
		return o.res, o.err
	case <-ctx.Done():
		return Result{}, fmt.Errorf("icmp probe %s: %w", ip, ctx.Err())
	}
}

func sendEcho(ip netip.Addr, timeout time.Duration) (Result, error) {
	if err := iphlpapi.Load(); err != nil {
		return Result{}, fmt.Errorf("%w: %w", ErrICMPUnsupported, err)
	}
	h, _, callErr := procIcmpCreateFile.Call()
	if h == invalidHandle || h == 0 {
		return Result{}, fmt.Errorf("IcmpCreateFile: %w", callErr)
	}
	defer procIcmpCloseHandle.Call(h) //nolint:errcheck // a close failure leaks one handle at worst; nothing to do

	b := ip.As4()
	// IPAddr is the address in network byte order, i.e. the bytes in memory order.
	dst := *(*uint32)(unsafe.Pointer(&b[0]))

	// The reply buffer must hold one ICMP_ECHO_REPLY, the echoed data, 8 bytes for an ICMP error and
	// an IO_STATUS_BLOCK (documented requirement). []uint64 keeps it 8-byte aligned for the struct.
	size := int(unsafe.Sizeof(icmpEchoReply{})) + len(echoPayload) + 8 + 16
	buf := make([]uint64, (size+7)/8)

	ms := uint32(timeout / time.Millisecond)
	n, _, callErr := procIcmpSendEcho.Call(
		h,
		uintptr(dst),
		uintptr(unsafe.Pointer(&echoPayload[0])),
		uintptr(len(echoPayload)),
		0,
		uintptr(unsafe.Pointer(&buf[0])),
		uintptr(len(buf)*8),
		uintptr(ms),
	)
	if n == 0 {
		var errno syscall.Errno
		if errors.As(callErr, &errno) && (isIPStatus(uint32(errno)) || errno == errorNetworkUnreachable || errno == errorHostUnreachable) {
			return Result{Up: false}, nil
		}
		return Result{}, fmt.Errorf("IcmpSendEcho %s: %w", ip, callErr)
	}
	reply := (*icmpEchoReply)(unsafe.Pointer(&buf[0]))
	// A "destination unreachable" generated by a router (or by this host for an unresolvable LAN
	// address) also counts as a reply: only a successful echo from the target itself means up.
	if reply.Status != ipSuccess || reply.Address != dst {
		return Result{Up: false}, nil
	}
	return Result{Up: true, RTT: time.Duration(reply.RoundTripTime) * time.Millisecond}, nil
}

func isIPStatus(code uint32) bool {
	return code >= ipStatusBase && code <= ipStatusBase+50
}
